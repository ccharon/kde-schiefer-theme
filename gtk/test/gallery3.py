#!/usr/bin/env python3
"""GTK3-Testgalerie für Schiefer. Fenster mit Kopfleiste (CSD) wie Firefox/Thunderbird."""
import sys
import gi
gi.require_version("Gtk", "3.0")
from gi.repository import Gtk, GLib, Gio  # noqa: E402

win = Gtk.Window(title="GTK3-Galerie")
win.set_default_size(980, 600)
hb = Gtk.HeaderBar(title="GTK3-Galerie", subtitle="Schiefer", show_close_button=True)
menubtn = Gtk.MenuButton()
menu = Gio.Menu()
menu.append("Öffnen …", "app.x")
menu.append("Speichern", "app.x")
sec = Gio.Menu()
sec.append("Beenden", "app.x")
menu.append_section(None, sec)
menubtn.set_menu_model(menu)
menubtn.set_use_popover(True)
menubtn.add(Gtk.Image.new_from_icon_name("open-menu-symbolic", Gtk.IconSize.BUTTON))
hb.pack_end(menubtn)
hb.pack_start(Gtk.Button.new_from_icon_name("go-previous-symbolic", Gtk.IconSize.BUTTON))
win.set_titlebar(hb)

outer = Gtk.Box(orientation=Gtk.Orientation.VERTICAL)
win.add(outer)

# Menüleiste
mb = Gtk.MenuBar()
for name in ("Datei", "Bearbeiten", "Ansicht", "Hilfe"):
    mb.append(Gtk.MenuItem(label=name))
outer.pack_start(mb, False, False, 0)

# Werkzeugleiste
tb = Gtk.Toolbar()
for icon, label in (("document-new", "Neu"), ("document-open", "Öffnen")):
    b = Gtk.ToolButton(icon_name=icon, label=label)
    b.set_is_important(True)
    tb.insert(b, -1)
tb.insert(Gtk.SeparatorToolItem(), -1)
t = Gtk.ToggleToolButton(icon_name="view-preview", label="Vorschau")
t.set_active(True)
t.set_is_important(True)
tb.insert(t, -1)
outer.pack_start(tb, False, False, 0)

nb = Gtk.Notebook()
outer.pack_start(nb, True, True, 0)
grid = Gtk.Box(spacing=8, margin=8)
nb.append_page(grid, Gtk.Label(label="Bedienelemente"))
nb.append_page(Gtk.Label(label="leer"), Gtk.Label(label="Zweite"))
nb.append_page(Gtk.Label(label="leer"), Gtk.Label(label="Dritte"))

# Spalte 1: Knöpfe und Auswahl
c1 = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6)
grid.pack_start(c1, False, False, 0)
f = Gtk.Frame(label="Knöpfe")
b = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6, margin=8)
f.add(b)
b.add(Gtk.Button(label="Standard"))
sa = Gtk.Button(label="Empfohlen")
sa.get_style_context().add_class("suggested-action")
b.add(sa)
tg = Gtk.ToggleButton(label="Eingerastet")
tg.set_active(True)
b.add(tg)
d = Gtk.Button(label="Deaktiviert")
d.set_sensitive(False)
b.add(d)
fl = Gtk.Button(label="Flach")
fl.set_relief(Gtk.ReliefStyle.NONE)
b.add(fl)
b.add(Gtk.LinkButton(uri="https://kde.org", label="Verweis"))
c1.add(f)
f = Gtk.Frame(label="Auswahl")
b = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=4, margin=8)
f.add(b)
cb = Gtk.CheckButton(label="Checkbox an")
cb.set_active(True)
b.add(cb)
b.add(Gtk.CheckButton(label="Checkbox aus"))
inc = Gtk.CheckButton(label="Teilweise")
inc.set_inconsistent(True)
b.add(inc)
r1 = Gtk.RadioButton(label="Option A")
b.add(r1)
b.add(Gtk.RadioButton.new_with_label_from_widget(r1, "Option B"))
hs = Gtk.Box(spacing=8)
sw = Gtk.Switch()
sw.set_active(True)
hs.add(sw)
hs.add(Gtk.Switch())
b.add(hs)
c1.add(f)

# Spalte 2: Eingaben
c2 = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6)
grid.pack_start(c2, False, False, 0)
f = Gtk.Frame(label="Eingaben")
g = Gtk.Grid(row_spacing=6, column_spacing=8, margin=8)
f.add(g)


def row(i, label, w):
    lab = Gtk.Label(label=label, xalign=1)
    g.attach(lab, 0, i, 1, 1)
    g.attach(w, 1, i, 1, 1)


e = Gtk.Entry(text="abc")
row(0, "Text:", e)
combo = Gtk.ComboBoxText()
for x in ("itemA", "itemB"):
    combo.append_text(x)
combo.set_active(0)
row(1, "ComboBox:", combo)
ec = Gtk.ComboBoxText.new_with_entry()
ec.append_text("editierbar")
ec.set_active(0)
row(2, "Editierbar:", ec)
row(3, "SpinButton:", Gtk.SpinButton.new_with_range(0, 100, 1))
sc = Gtk.Scale.new_with_range(Gtk.Orientation.HORIZONTAL, 0, 100, 1)
sc.set_value(40)
sc.set_draw_value(False)
sc.set_hexpand(True)
row(4, "Regler:", sc)
sc2 = Gtk.Scale.new_with_range(Gtk.Orientation.HORIZONTAL, 0, 100, 1)
sc2.set_value(70)
sc2.set_draw_value(False)
for v in range(0, 101, 10):
    sc2.add_mark(v, Gtk.PositionType.BOTTOM, None)
row(5, "Mit Skala:", sc2)
pb = Gtk.ProgressBar(fraction=0.6, show_text=True)
row(6, "Fortschritt:", pb)
lb = Gtk.LevelBar(value=0.4)
row(7, "Pegel:", lb)
search = Gtk.SearchEntry(placeholder_text="Suchen …")
row(8, "Suche:", search)
c2.add(f)
ex = Gtk.Expander(label="Ausklappbar")
ex.add(Gtk.Label(label="Inhalt"))
ex.set_expanded(True)
c2.add(ex)

# Spalte 3: Ansichten
c3 = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6)
grid.pack_start(c3, True, True, 0)
store = Gtk.TreeStore(str, str)
for i in range(1, 4):
    it = store.append(None, [f"Ordner {i}", "–"])
    store.append(it, ["datei.txt", "4 KB"])
tv = Gtk.TreeView(model=store)
for i, title in enumerate(("Name", "Größe")):
    col = Gtk.TreeViewColumn(title, Gtk.CellRendererText(), text=i)
    col.set_resizable(True)
    tv.append_column(col)
tv.expand_row(Gtk.TreePath.new_first(), False)
tv.get_selection().select_path(Gtk.TreePath.new_from_string("0:0"))
sw1 = Gtk.ScrolledWindow(min_content_height=150)
sw1.set_shadow_type(Gtk.ShadowType.IN)
sw1.add(tv)
c3.pack_start(sw1, True, True, 0)
txt = Gtk.TextView()
txt.get_buffer().set_text("\n".join(["Mehrzeiliger Text"] * 20))
sw2 = Gtk.ScrolledWindow(min_content_height=120)
sw2.set_shadow_type(Gtk.ShadowType.IN)
sw2.set_policy(Gtk.PolicyType.ALWAYS, Gtk.PolicyType.ALWAYS)
sw2.add(txt)
c3.pack_start(sw2, True, True, 0)
lst = Gtk.ListBox()
for x in ("Eintrag A", "Eintrag B", "Eintrag C"):
    lst.add(Gtk.Label(label=x, xalign=0, margin=4))
lst.select_row(lst.get_row_at_index(1))
fr = Gtk.Frame()
fr.add(lst)
c3.pack_start(fr, False, False, 0)

sb = Gtk.Statusbar()
sb.push(0, "Bereit")
outer.pack_end(sb, False, False, 0)

win.connect("destroy", Gtk.main_quit)
win.show_all()
if "--popover" in sys.argv:
    GLib.timeout_add(1500, lambda: menubtn.set_active(True) and False)
Gtk.main()
